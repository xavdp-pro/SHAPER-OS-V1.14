export const LOCALES = ['fr', 'es', 'en'];

export const LOCALE_FLAGS = {
  fr: { flag: '🇫🇷', label: 'Français' },
  es: { flag: '🇪🇸', label: 'Español' },
  en: { flag: '🇬🇧', label: 'English' },
};

const STORAGE_KEY = 'helm-locale';

export function normalizeLocale(raw) {
  const v = String(raw || 'fr').toLowerCase().slice(0, 2);
  return LOCALES.includes(v) ? v : 'fr';
}

/** Read ?lang= / ?locale= from a URL (or current location). */
export function localeFromSearch(search = '') {
  try {
    const q = new URLSearchParams(
      String(search || (typeof window !== 'undefined' ? window.location.search : '')).replace(/^\?/, ''),
    );
    const raw = q.get('lang') || q.get('locale') || q.get('hl');
    if (!raw) return null;
    const code = normalizeLocale(raw);
    return LOCALES.includes(String(raw).toLowerCase().slice(0, 2)) ? code : null;
  } catch {
    return null;
  }
}

function localeFromNavigator() {
  try {
    const nav = typeof navigator !== 'undefined'
      ? (navigator.languages?.[0] || navigator.language || '')
      : '';
    const code = String(nav).toLowerCase().slice(0, 2);
    return LOCALES.includes(code) ? code : null;
  } catch {
    return null;
  }
}

/**
 * Resolve UI locale:
 * 1. URL ?lang=en|fr|es (demo / shareable links) — explicit, persisted
 * 2. localStorage (previous choice or first-visit detection)
 * 3. browser language (first visit only) — persisted so it sticks
 * 4. fr
 */
export function loadLocale() {
  const fromUrl = localeFromSearch();
  if (fromUrl) {
    saveLocale(fromUrl);
    return fromUrl;
  }
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && LOCALES.includes(String(stored).toLowerCase().slice(0, 2))) {
      return normalizeLocale(stored);
    }
  } catch {
    /* ignore */
  }
  const detected = localeFromNavigator() || 'fr';
  saveLocale(detected);
  return detected;
}

export function saveLocale(locale) {
  try {
    localStorage.setItem(STORAGE_KEY, normalizeLocale(locale));
  } catch {
    /* ignore */
  }
}

/** Keep ?lang= in the address bar when the user picks a flag (shareable). */
export function syncLocaleQuery(locale) {
  if (typeof window === 'undefined') return;
  try {
    const url = new URL(window.location.href);
    const next = normalizeLocale(locale);
    if (url.searchParams.get('lang') === next) return;
    url.searchParams.set('lang', next);
    url.searchParams.delete('locale');
    url.searchParams.delete('hl');
    window.history.replaceState({}, '', `${url.pathname}${url.search}${url.hash}`);
  } catch {
    /* ignore */
  }
}

export function elevenLabsLanguageCode(locale) {
  return normalizeLocale(locale);
}

