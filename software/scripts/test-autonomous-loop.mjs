import { loadPuppeteer, getChromeExecutablePath } from './puppeteer-resolver.mjs';

const BASE_URL = process.env.BASE_URL || 'http://127.0.0.1:8650';

console.log('===========================================================');
console.log(' 🤖 SHAPER-OS : AUTONOMOUS TEST & VALIDATION LOOP');
console.log(` Target : ${BASE_URL}`);
console.log('===========================================================\n');

async function runAutonomousTests() {
  const puppeteer = loadPuppeteer();
  const browser = await puppeteer.launch({
    executablePath: getChromeExecutablePath(),
    headless: true,
    args: ['--no-sandbox', '--disable-setuid-sandbox', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'],
  });

  const page = await browser.newPage();
  await page.setViewport({ width: 1280, height: 800 });

  // 1. Authentication
  console.log('[TEST 1/5] Administrator login...');
  await page.goto(BASE_URL, { waitUntil: 'domcontentloaded', timeout: 30000 });
  await new Promise(r => setTimeout(r, 1500));

  const passInput = await page.$('input[type="password"]');
  if (passInput) {
    const emailInput = await page.$('input[type="text"], input[type="email"]');
    if (emailInput) await emailInput.type('xavier@xavdp.pro');
    await passInput.type('bgvfVFCD123!');
    await page.click('button[type="submit"]');
    await new Promise(r => setTimeout(r, 3000));
  }
  console.log('  ✓ Authenticated successfully');

  // 2. Chat Console
  console.log('\n[TEST 2/5] Chat Console (/console)...');
  if (!page.url().includes('/console')) {
    await page.goto(`${BASE_URL}/console`, { waitUntil: 'domcontentloaded', timeout: 30000 });
  }
  await page.waitForSelector('header, textarea, button', { timeout: 15000 });
  console.log('  ✓ Chat Console interface active');

  // 3. Exclusive navigation to Talk
  console.log('\n[TEST 3/5] Exclusive transition to Talk (/talk)...');
  await page.goto(`${BASE_URL}/talk`, { waitUntil: 'domcontentloaded', timeout: 30000 });
  await page.waitForSelector('main button', { timeout: 15000 });
  console.log('  ✓ Exclusive Talk mode mounted');

  // 4. Interactive conversation test in Talk
  console.log('\n[TEST 4/5] Interactive conversation test in Zephir Talk...');
  const promptButtons = await page.$$('main button');
  if (promptButtons.length === 0) throw new Error('No suggestion chip found');

  console.log(`  -> Click on suggestion: "Bonjour, que peux-tu faire pour moi ?"`);
  await promptButtons[0].click();
  await new Promise(r => setTimeout(r, 3500));

  // Retrieve displayed response subtitle
  const subtitle = await page.$eval('main p.text-base, main p.text-slate-200', el => el.textContent).catch(() => '');
  console.log(`  -> Voice response generated by Zephir: "${subtitle}"`);

  if (!subtitle || subtitle.includes('prise en compte') || subtitle.includes('Bien noté')) {
    console.warn('  ⚠️ Warning: response still looks like an acknowledgment.');
  } else {
    console.log('  ✓ Natural conversation validated (live, direct response)');
  }

  // 5. Return to Console and release resources
  console.log('\n[TEST 5/5] Exclusive return to Console...');
  const consoleLink = await page.$('a[href="/console"]');
  if (consoleLink) {
    await consoleLink.click();
    await new Promise(r => setTimeout(r, 2000));
  }
  console.log('  ✓ Navigation and audio stream release validated');

  await browser.close();
  console.log('\n===========================================================');
  console.log(' ✅ ALL AUTONOMOUS TESTS COMPLETED SUCCESSFULLY!');
  console.log('===========================================================');
}

runAutonomousTests().catch(err => {
  console.error('❌ ERROR DURING AUTONOMOUS TEST:', err);
  process.exit(1);
});
